# H1-2 Action Scale.  Same 0.25 * effort / stiffness form used by g1.py, h2.py
# and PR #112's x2_ultra.py.  (The prose in new_embodiments.md omits the 0.25;
# every implementation in the tree has it, so the code is followed here.)
H1_2_ACTION_SCALE = {}
for a in H1_2_CFG.actuators.values():
    e = a.effort_limit_sim
    s = a.stiffness
    names = a.joint_names_expr
    if not isinstance(e, dict):
        e = dict.fromkeys(names, e)
    if not isinstance(s, dict):
        s = dict.fromkeys(names, s)
    for n in names:
        if n in e and n in s and s[n]:
            H1_2_ACTION_SCALE[n] = 0.25 * e[n] / s[n]
