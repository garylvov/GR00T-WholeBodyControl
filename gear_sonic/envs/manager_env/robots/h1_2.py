"""Unitree **H1-2** (27 DOF / 28 bodies) embodiment for SONIC.

NAMING TRAP: this is the Unitree **H1-2**, which is a *different robot* from the
Unitree **H2** in ``h2.py``.  Do not copy numbers between the two files.

Assets
------
``data/assets/robot_description/urdf/h1_2/h1_2.urdf`` and
``data/assets/robot_description/mjcf/h1_2.xml`` are both GENERATED by
``gear_sonic/scripts/gen_h1_2_assets.py`` from our r13 USD factory's blessed
no-fingers source (ProtoMotions ``h1_2_box_feet.xml``, the exact
primitive-collision model our H1-2 tracker policy was trained on).  No vendor
URDF is in this path -- see that script's docstring for the provenance argument.

The only structural delta vs. our canonical model is that the massless marker
body ``head_aux`` is dropped, so that ``num_bodies == num_dof + 1`` as SONIC's
order converter requires.  Its constant offset is preserved below as
``H1_2_HEAD_OFFSET_IN_TORSO`` so head-referenced rewards stay expressible.

Index tables
------------
The five tables below are GENERATED by
``gear_sonic/scripts/gen_h1_2_order_tables.py`` and frozen here as literals.
Do not hand-edit; re-run the generator (``--check`` fails the build if these
literals drift from the assets).  That script also proves its convention by
reproducing upstream's own published H2 tables from ``h2.xml`` + ``h2.py``, and
cross-checks the derived Isaac Lab order against the *independently measured*
order frozen in our r13 USD factory.

Semantics (same as G1/H2; note PR #112's ``x2_ultra.py`` names its constants the
other way round and swaps them in the dict):

    ISAACLAB_TO_MUJOCO_*[k] = IsaacLab index of the k-th MuJoCo entry
    MUJOCO_TO_ISAACLAB_*[i] = MuJoCo index of the i-th IsaacLab entry
"""

